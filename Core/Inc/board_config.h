#ifndef __BOARD_CONFIG_H
#define __BOARD_CONFIG_H

#include "main.h"   /* 复用 CubeMX 生成的原始引脚标签 */

/* =====================================================================
 *  一、4 路继电器映射
 *  约定: "报警 = 吸合(SET)"。常开/常闭由客户接线决定, 程序统一吸合。
 *        K1~K3 逻辑完全一致; K4 防火阀走独立状态机(见 temperature.c)。
 * ===================================================================== */
#define K1_ALARM_Port    Relay_24_GPIO_Port    /* PB5  警报   */
#define K1_ALARM_Pin     Relay_24_Pin
#define K2_FAN_Port      Relay_220_GPIO_Port   /* PB6  风机   */
#define K2_FAN_Pin       Relay_220_Pin
#define K3_GAS_Port      Relay3_GPIO_Port      /* PA0  断气阀 */
#define K3_GAS_Pin       Relay3_Pin
#define K4_DAMPER_Port   Relay4_GPIO_Port      /* PA1  防火阀 */
#define K4_DAMPER_Pin    Relay4_Pin

/* =====================================================================
 *  二、防火阀(K4)方案 —— 已按执行器铭牌定稿 (AC220V, 三线制, 带内置限位)
 *
 *  【K4 接法, 与丝印一致】火线 L 进 COM, 红线接零线 N (不过板):
 *      K4 COM  <-  客户 220V 火线 L
 *      K4 NC   ->  黑线(开阀)   平时(释放)导通 => 阀保持开
 *      K4 NO   ->  蓝线(关阀)   报警(吸合)导通 => 阀关闭
 *      红线    ->  零线 N       (客户直接接)
 *  【断电失效安全】设备断电 => K4 释放 => 走 NC => 开阀线 => 阀常开 (防火阀应有状态)。
 *  【限位确认】铭牌 黄/绿/白 = 无源位置反馈 (绿-黄=常闭, 绿-白=常开),
 *              说明内部有限位、到位自停 => 持续供电保持无忧, 程序不掐行程时间。
 *
 *  方案开关: 1 = 带限位(单路 K4, 本项目定稿) / 0 = 无限位(双路 K4/K5, 仅备用)
 * ===================================================================== */
#define DAMPER_HAS_LIMIT_SWITCH   1

#if (DAMPER_HAS_LIMIT_SWITCH == 0)
  /* 备用: 无限位双路方案。本执行器已确认带限位, 不启用;
   * K5 焊位板上保留但不焊(留着不亏)。如换无限位执行器再启用并填引脚。 */
  #define K5_DAMPER2_Port  GPIOA
  #define K5_DAMPER2_Pin   GPIO_PIN_4     /* TODO: 换成新板实际引脚, 并在 gpio.c 里加 GPIO 初始化 */
  #define DAMPER_TRAVEL_MS  30000         /* TODO: 无限位时的行程时间(s 级) */
#endif

/* =====================================================================
 *  三、阈值出厂默认值
 *    上电时若 Flash 无有效数据(首次烧录), 使用此默认值。
 *    分组现状(见 temperature.c): CH1~CH7 用阈值1, CH8 用阈值2。
 * ===================================================================== */
#define TEMP_TH1_DEFAULT   100   /* TODO: 等客户实验数据确定 (CH1-CH7 组) */
#define TEMP_TH2_DEFAULT   100   /* TODO: 等客户实验数据确定 (CH8 组)    */

/* =====================================================================
 *  四、报警抑制期
 *    复位后此时间内不再触发新的温度报警(防余温反复报警)。
 * ===================================================================== */
#define ALARM_COOLDOWN_MS  (3UL * 60 * 1000)   /* 3 分钟, 现场实测后可调 */

/* =====================================================================
 *  五、完整引脚映射参考表 (原始标签见 main.h, 由 CubeMX 维护)
 * ---------------------------------------------------------------------
 *   继电器   K1 警报    PB5   Relay_24
 *            K2 风机    PB6   Relay_220
 *            K3 断气阀  PA0   Relay3
 *            K4 防火阀  PA1   Relay4   (COM=火线L, NC=黑线开阀, NO=蓝线关阀; AC220V)
 *            K5 开阀*   ?     (备用, 已确认带限位不启用; 板上保留焊位不焊)
 *   指示灯   红/黄/蓝   PB14/PB15/PB13   LED_Red / LED_Yellow / LED_Blue
 *            板载 LED   PC13             LED
 *   按键     SET/加/减/移位   PB3/PB4/PB0/PB1   Btn1/Btn2/Btn3/Btn4
 *            手动/复位  PA12/PA15        Manual_Btn / Reset_Btn
 *   数码管   组1 DS/SH/ST  PA5/PA6/PA7   SDI1/SCLK1/LOAD1
 *            组2 DS/SH/ST  PB7/PB8/PB9   SDI2/SCLK2/LOAD2
 *   串口     UART1 上位机  PA9/PA10
 *            UART2 温度模块 PA2/PA3
 * ===================================================================== */

#endif /* __BOARD_CONFIG_H */
